const fs = require('fs');
const path = require('path');
const data = require('./data.js');

const BOOKS_DIR = path.join(__dirname, 'books_library');
if (!fs.existsSync(BOOKS_DIR)) {
    fs.mkdirSync(BOOKS_DIR, { recursive: true });
}

console.log("Generating books library...");

let totalGenerated = 0;

data.authors.forEach((author, aIdx) => {
    author.books.forEach((book, bIdx) => {
        const safeAuthor = author.name.replace(/[\s\.]+/g, '_');
        const safeTitle = book.title.replace(/[\\/:*?"<>|\s]+/g, '_').slice(0, 50);
        const fileNameBase = `${aIdx + 1}_${safeAuthor}_${safeTitle}`;

        const bookContent = `================================================================================
                    ЭЛЕКТРОННАЯ БИБЛИОТЕКА «СПЕКТР ГЕОПОЛИТИКИ»
                   ФУНДАМЕНТАЛЬНОЕ ИССЛЕДОВАНИЕ ПО МИРОВОЙ СТРАТЕГИИ
================================================================================

НАЗВАНИЕ ТРУДА: ${book.title.toUpperCase()}
ОРИГИНАЛЬНОЕ НАЗВАНИЕ: ${book.titleOrig}
ГОД ПЕРВОГО ИЗДАНИЯ: ${book.year} год

АВТОР: ${author.name} (${author.nameOrig})
ГОДЫ ЖИЗНИ: ${author.years}
ГОСУДАРСТВО / ШКОЛА: ${author.country} | ${author.role}
ГЕОПОЛИТИЧЕСКАЯ ТРАДИЦИЯ: ${author.school.toUpperCase()}

ЭПИГРАФ ИЗ ТРУДОВ МЫСЛИТЕЛЯ:
«${author.quote}»

================================================================================
                      РАЗДЕЛ I. ИСТОРИЧЕСКИЙ КОНТЕКСТ И АННОТАЦИЯ
================================================================================
${book.description}

Историческая справка:
Работа создавалась в эпоху масштабных изменений мирового баланса сил. Автор 
обобщил предшествующий опыт дипломатических войн, географических открытий и 
территориальной экспансии, чтобы сформулировать объективные пространственные 
законы, управляющие возвышением и упадком мировых держав.

================================================================================
             РАЗДЕЛ II. СИСТЕМНЫЕ ПОЛОЖЕНИЯ И СТРАТЕГИЧЕСКИЕ ТЕЗИСЫ
================================================================================
${book.keyPoints.map((kp, idx) => `[ТЕЗИС ${idx + 1}]:\n${kp}`).join('\n\n')}

================================================================================
                 РАЗДЕЛ III. БАЗОВЫЙ ПОНЯТИЙНЫЙ АППАРАТ АВТОРА
================================================================================
В основу концептуального аппарата книги заложены фундаментальные понятия:
${author.mainConcepts.map((c, idx) => `  ${idx + 1}. «${c}» — фундаментальная категория пространственного анализа, определяющая характер взаимоотношений центра и периферии.`).join('\n')}

================================================================================
             РАЗДЕЛ IV. БИОГРАФИЧЕСКИЙ ОЧЕРК И ФОРМИРОВАНИЕ МЫСЛИТЕЛЯ
================================================================================
${author.bio}

Влияние на внешнюю политику:
Идеи автора легли в основу доктрин генеральных штабов и внешнеполитических ведомств,
определяя стратегию развертывания вооруженных сил, морского владычества и 
создания коалиций на протяжении десятилетий.

================================================================================
             РАЗДЕЛ V. ЗНАЧЕНИЕ ДЛЯ МИРОВОЙ ГЕОПОЛИТИКИ И АНАЛИЗ ДЛЯ XXI ВЕКА
================================================================================
Историческое значение:
${book.significance}

Актуальность для XXI века:
В эпоху перехода к многополярному мироустройству положения данной книги служат 
критическим ключом к пониманию современных конфликтов:
1. Борьба за ключевые сухопутные и океанские маршруты торговли;
2. Противостояние коалиций морской силы (Sea Power / Римленд) и континентальных держав (Хартленд);
3. Формирование закрытых ресурсных зон и суверенных экономических пространств.

================================================================================
Издание подготовлено цифровым порталом «Спектр геополитики»
Сайт проекта: http://localhost:3000
Дата формирования электронной копии: ${new Date().toLocaleDateString('ru-RU')}
Лицензия: Открытый доступ для исследователей и аналитиков
================================================================================
`;

        // Write TXT format
        fs.writeFileSync(path.join(BOOKS_DIR, `${fileNameBase}.txt`), bookContent, 'utf-8');

        // Write MD format
        const mdContent = `# ${book.title}
*Оригинальное название:* **${book.titleOrig}** (${book.year} г.)  
*Автор:* **${author.name}** (${author.nameOrig}), ${author.years}  
*Геополитическая школа:* ${author.school.toUpperCase()} (${author.country})

> «${author.quote}»

---

## 1. Исторический контекст и аннотация
${book.description}

## 2. Ключевые тезисы работы
${book.keyPoints.map(kp => `- **${kp}**`).join('\n')}

## 3. Базовый понятийный аппарат
${author.mainConcepts.map(c => `- \`${c}\``).join('\n')}

## 4. Биография автора и наследие
${author.bio}

## 5. Значение для мировой геополитики
${book.significance}

---
*Электронное издание портала «Спектр геополитики» (http://localhost:3000)*
`;
        fs.writeFileSync(path.join(BOOKS_DIR, `${fileNameBase}.md`), mdContent, 'utf-8');

        totalGenerated++;
    });
});

console.log(`Generated ${totalGenerated} complete books in TXT and MD formats in ${BOOKS_DIR}`);
